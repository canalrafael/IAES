"""
Results Analyzer for Stage 2
=============================
Reads the CSV generated by run_stage2_sweep.py and produces the figures and
summary table required for the paper.

Outputs (in results/figures/):
  - Fig 1: Manipulation Rate vs. Contention Workers (Line plot)
  - Fig 2: Delta_ctrl vs. Contention Workers (Bar chart with 95% CI)
  - Fig 3: Heatmap of Manipulation Rate (RTT x BW)
  - Fig 4: Box plots of Latencies (J(k^0, 0), J(k^0, a), J(k^a, 0))
  - Tab 1: Summary statistics CSV
"""

import argparse
import os
import glob
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

FIGURES_DIR = os.path.join("results", "figures")


def load_latest_csv(input_path: str = None) -> str:
    if input_path is not None:
        return input_path
    csv_files = glob.glob(os.path.join("results", "raw_results_*.csv"))
    if not csv_files:
        raise FileNotFoundError("No raw_results CSV found in results/")
    latest_csv = max(csv_files, key=os.path.getctime)
    return latest_csv


def generate_figures(df: pd.DataFrame, out_dir: str):
    os.makedirs(out_dir, exist_ok=True)
    
    # Common seaborn settings
    sns.set_theme(style="whitegrid")
    
    # -------------------------------------------------------------------------
    # Fig 1: Manipulation Rate vs Workers (Line plot)
    # -------------------------------------------------------------------------
    plt.figure(figsize=(8, 5))
    # Group by model, workers. Calculate mean of decision_changed * 100
    df['success_pct'] = df['decision_changed'] * 100.0
    sns.lineplot(data=df, x='workers', y='success_pct', hue='model', marker='o', errorbar=None)
    
    plt.title("Adversarial Manipulation Rate vs. Contention Intensity")
    plt.xlabel("Number of Contention Workers")
    plt.ylabel("Manipulation Success Rate (%)")
    plt.ylim(0, 105)
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, "fig1_manipulation_rate.png"), dpi=300)
    plt.savefig(os.path.join(out_dir, "fig1_manipulation_rate.pdf"))
    plt.close()

    # -------------------------------------------------------------------------
    # Fig 2: Delta_ctrl vs Workers (Bar chart with CI)
    # -------------------------------------------------------------------------
    plt.figure(figsize=(8, 5))
    # Only include trials where manipulation succeeded (optional, but makes sense for delta_ctrl)
    # or just show expected value over all trials
    sns.barplot(data=df, x='workers', y='delta_probe_ctrl_ms', hue='model', capsize=.1)
    
    plt.title(r"Control-Induced Amplification ($\Delta_{ctrl}$) vs. Contention")
    plt.xlabel("Number of Contention Workers")
    plt.ylabel(r"$\Delta_{ctrl}$ (ms)")
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, "fig2_delta_ctrl.png"), dpi=300)
    plt.savefig(os.path.join(out_dir, "fig2_delta_ctrl.pdf"))
    plt.close()
    
    # -------------------------------------------------------------------------
    # Fig 3: Heatmap of Manipulation Rate (RTT x BW)
    # -------------------------------------------------------------------------
    # Aggregate over all models and workers, or pick a specific worker count
    # Let's aggregate over all models and workers=max to show network impact
    max_workers = df['workers'].max()
    df_net = df[df['workers'] == max_workers]
    
    if len(df_net) > 0 and len(df_net['rtt_ms'].unique()) > 1 and len(df_net['bw_mbps'].unique()) > 1:
        heatmap_data = df_net.pivot_table(
            values='success_pct', 
            index='rtt_ms', 
            columns='bw_mbps', 
            aggfunc='mean'
        )
        plt.figure(figsize=(7, 5))
        sns.heatmap(heatmap_data, annot=True, fmt=".1f", cmap="YlOrRd", vmin=0, vmax=100)
        plt.title(f"Manipulation Rate (%) by Network [Workers={max_workers}]")
        plt.xlabel("Bandwidth (Mbps)")
        plt.ylabel("RTT (ms)")
        plt.tight_layout()
        plt.savefig(os.path.join(out_dir, "fig3_heatmap.png"), dpi=300)
        plt.savefig(os.path.join(out_dir, "fig3_heatmap.pdf"))
        plt.close()

    # -------------------------------------------------------------------------
    # Fig 4: Box plots of Latencies
    # -------------------------------------------------------------------------
    # Melt the dataframe to have a 'phase' column for the three latencies
    melted = df.melt(
        id_vars=['model', 'workers', 'trial'], 
        value_vars=['J_k0_benign_ms', 'J_k0_attacked_ms', 'J_ka_benign_ms'],
        var_name='Phase', 
        value_name='Latency (ms)'
    )
    # Rename phases for the plot
    phase_map = {
        'J_k0_benign_ms': 'Nominal (k^0)',
        'J_k0_attacked_ms': 'Attacked (k^0)',
        'J_ka_benign_ms': 'Post-Attack (k^a)'
    }
    melted['Phase'] = melted['Phase'].map(phase_map)
    
    # Just show for the highest worker count to avoid clutter
    df_box = melted[melted['workers'] == max_workers]
    
    plt.figure(figsize=(10, 6))
    sns.boxplot(data=df_box, x='model', y='Latency (ms)', hue='Phase')
    plt.title(f"End-to-End Latency by Phase [Workers={max_workers}]")
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, "fig4_boxplots.png"), dpi=300)
    plt.savefig(os.path.join(out_dir, "fig4_boxplots.pdf"))
    plt.close()
    
    # -------------------------------------------------------------------------
    # Tab 1: Summary Statistics
    # -------------------------------------------------------------------------
    summary = df.groupby(['model', 'workers', 'rtt_ms', 'bw_mbps']).agg(
        Trials=('trial', 'count'),
        Manipulation_Rate_Pct=('success_pct', 'mean'),
        Delta_phys_mean=('delta_phys_ms', 'mean'),
        Delta_phys_std=('delta_phys_ms', 'std'),
        Delta_ctrl_mean=('delta_probe_ctrl_ms', 'mean'),
        Delta_ctrl_std=('delta_probe_ctrl_ms', 'std'),
    ).reset_index()
    
    summary_path = os.path.join(out_dir, "tab1_summary.csv")
    summary.to_csv(summary_path, index=False)
    print(f"Figures and summary table generated in {out_dir}/")


def main():
    parser = argparse.ArgumentParser(description="Analyze Stage 2 Sweep Results")
    parser.add_argument("--input", type=str, default=None, help="Path to raw_results CSV")
    args = parser.parse_args()

    csv_path = load_latest_csv(args.input)
    print(f"Analyzing {csv_path}...")
    df = pd.read_csv(csv_path)
    generate_figures(df, FIGURES_DIR)


if __name__ == "__main__":
    main()
